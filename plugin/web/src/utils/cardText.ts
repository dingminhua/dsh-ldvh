/**
 * 卡面文本的 Markdown 标记剥离（**单一实现**）。
 *
 * 为什么需要：**卡面是纯文本插值**（无 Markdown 渲染器，见 `docs/10`「卡面是扫读窗口」），
 * 而字段与正文里常带 Markdown 标记——纯文本插值会把 `**加粗**`、`` `标识符` `` 的
 * **标记本身**显示给读者。**「不解析 Markdown」不等于「不显示标记」**，故渲染前须剥离。
 *
 * 与详情面的分工：详情面用 `react-markdown`（`SummaryText`）**正常渲染**标记，语义
 * （加粗＝强调、反引号＝标识符）被保留；**数据层不改**——剥的只是卡面这一层的显示。
 * 故同一个源文本在详情页与卡面上形态不同，这是有意的：两面读者不同（`docs/10`：卡面
 * 是扫读窗口、详情是阅读面）。
 *
 * 覆盖的标记（与仓库既有实现逐字一致，2026-09-24 由 `ObjectList` 提为共享）：
 * `# 标题` / `[ ]` `[x]` 复选框 / `` `行内代码` `` / `**加粗**` / `*斜体*`。
 * 不处理：代码围栏、链接、表格——卡面不承载这些（`gist` 与建议段已登记为纯文本；
 * 残留为逐条短句），出现即应暴露而非静默吞掉。
 *
 * 边界（如实声明）：本函数只**去标记**，不改变文字内容，也不解析任何 Markdown 语义；
 * 它不证明剥离后的文本「准确」或「可读」——那属写作纪律与 Human 阅读。
 */
export function stripCardMarkdown(value: string): string {
  return value
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => line
      .trim()
      .replace(/^#{1,6}\s+/, '')
      .replace(/\[[ xX]\]\s*/g, '')
      .replace(/`([^`]+)`/g, '$1')
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/\*([^*]+)\*/g, '$1')
      .trim())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
