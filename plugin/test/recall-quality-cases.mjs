/**
 * 判定某行是否属于「应得答案」。按标题前缀匹配，避免长标题差异导致误判。
 *
 * 这是**判定口径**而非仅测试辅助：消融工具必须与基线测试用同一判据，
 * 否则两侧的「命中」定义不同。
 */
export function isRelated(title, want) {
  if (want.length === 0) return false;
  return want.some((w) => title.includes(w.slice(0, 6)));
}
